"""Tests for the migration drift checker's parsing.

The failure mode worth guarding against is the checker that always passes. If
``probe_body`` returned "" for every input -- one bad ``split`` away -- CI would
go green forever while models and migrations drifted apart, and the check would
be worse than absent because it would be trusted.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

from check_migration_drift import probe_body

EMPTY = '''"""drift probe"""

def upgrade() -> None:
    # ### commands auto generated by Alembic - please adjust! ###
    pass
    # ### end Alembic commands ###


def downgrade() -> None:
    pass
'''

WITH_DRIFT = '''"""drift probe"""

def upgrade() -> None:
    # ### commands auto generated by Alembic - please adjust! ###
    op.add_column('stories', sa.Column('mood', sa.String(length=32), nullable=True))
    # ### end Alembic commands ###


def downgrade() -> None:
    op.drop_column('stories', 'mood')
'''


class TestProbeBody:
    def test_an_empty_probe_reports_no_drift(self):
        assert probe_body_of(EMPTY) == ""

    def test_a_real_change_is_reported(self):
        assert "add_column" in probe_body_of(WITH_DRIFT)

    def test_the_downgrade_is_not_mistaken_for_drift(self):
        """`downgrade` always has operations; reading it would always fail."""
        assert "drop_column" not in probe_body_of(WITH_DRIFT)

    def test_alembic_comments_are_not_drift(self):
        assert "auto generated" not in probe_body_of(WITH_DRIFT)

    def test_the_checker_can_actually_fail(self):
        """The property that makes the whole check worth having."""
        assert probe_body_of(EMPTY) != probe_body_of(WITH_DRIFT)


def probe_body_of(text: str) -> str:
    """Parse a migration file's upgrade body, via a real file on disk."""
    directory = Path(tempfile.mkdtemp())
    path = directory / "probe.py"
    path.write_text(text, encoding="utf-8")
    return probe_body(path)
